def nuspec(name, version):
    folder = os.path.join(PACKAGES, name.lower(), version.lower())
    path = os.path.join(folder, name.lower() + ".nuspec")
    with open(path, encoding="utf-8-sig") as f:
        text = f.read()

    def tag(t):
        m = re.search(rf"<{t}[^>]*>([^<]*)</{t}>", text)
        return m.group(1).strip() if m else ""

    m = re.search(r'<license type="(expression|file)">([^<]+)</license>', text)
    licence = (m.group(1), m.group(2)) if m else ("url", tag("licenseUrl"))
    return folder, tag("copyright"), licence, tag("projectUrl")


def main():
    with open(ASSETS, encoding="utf-8") as f:
        libraries = json.load(f)["libraries"]
    entries, files = [], {}
    for key, value in sorted(libraries.items(), key=lambda kv: kv[0].lower()):
        if value.get("type") != "package":
            continue
        name, version = key.split("/")
        if name.startswith(BUILD_ONLY):
            continue
        folder, copyright_line, (kind, licence), project = nuspec(name, version)
        if kind == "file":
            with open(os.path.join(folder, licence), encoding="utf-8-sig", errors="replace") as f:
                body = f.read().strip()
            if body not in files.values():
                files[str(len(files) + 1)] = body
            label = "Licence text " + next(k for k, v in files.items() if v == body)
        else:
            label = licence
        entries.append((name, version, label, copyright_line, project))

    out = [
        "SidePhase Mail - third-party notices",
        "=====================================",
        "",
        "SidePhase Mail is (c) SidePhase Studio. It includes the following third-party components, each under its",
        "own licence. The .NET runtime is also bundled (MIT licence, (c) .NET Foundation and Contributors), and",
        "e_sqlite3 contains SQLite, which is in the public domain (https://sqlite.org/copyright.html).",
        "",
        "Generated by scripts/release/update_third_party_notices.py from the shipped packages.",
        "",
    ]
    for name, version, label, copyright_line, project in entries:
        out.append(f"* {name} {version}")
        out.append(f"    Licence: {label}")
        if copyright_line:
            out.append(f"    Copyright: {copyright_line}")
        if project:
            out.append(f"    Project: {project}")
    out += ["", "-" * 72, "MIT licence (applies to the components marked MIT, with their copyright lines above)", "-" * 72, "", MIT,
            "", "-" * 72, "Apache License 2.0 (components marked Apache-2.0)", "-" * 72, "", APACHE]
    for number, body in files.items():
        out += ["", "-" * 72, f"Licence text {number}", "-" * 72, "", body]
    with open(os.path.join(ROOT, "THIRD-PARTY-NOTICES.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(entries)} components, {len(files)} included licence texts")


if __name__ == "__main__":
    sys.exit(main())
