"""Regenerates THIRD-PARTY-NOTICES.txt from the packages the app actually ships with.

Run after changing package references:
    dotnet restore src/SidePhase.Mail.App -p:Platform=x64 -r win-x64 -p:EnableWindowsTargeting=true
    python3 scripts/release/update_third_party_notices.py

Names, versions, licences and copyright lines come from the restored packages' .nuspec files; licence texts come
from the packages where they include one. Build-only packages (SDK build tools) aren't shipped and are left out.
"""
